const assert=require('node:assert/strict');
const {buildControlDecision:build}=require('../docs/frontend-prototype/automation/control-commands.js');
const item=(kind,context,options=[])=>({kind,objectId:'object',version:3,evidenceToken:'inbox-context-hash',contextJson:JSON.stringify(context),options});
const question=build(item('question',{fromVersion:7,toVersion:11}));
assert.equal(question.expectedFromVersion,7);assert.equal(question.expectedToVersion,11);
const choice=build(item('choice',{members:[{packageId:'unaccepted',approved:true,accepted:false},{packageId:'winner',approved:true,accepted:true,taskId:'real-task',evidenceToken:'actual-outcome-token'}]}));
assert.equal(choice.winner,'winner');assert.equal(choice.expectedEvidenceToken,'actual-outcome-token');
assert.notEqual(choice.expectedEvidenceToken,'inbox-context-hash');
assert.equal(build(item('knowledge',{},['reject'])).action,'RejectProposal');
assert.equal(build(item('restructure',{},['reject'])).action,'Reject');
assert.throws(()=>build(item('review',{})));
const actualQuestion=build(item('question',{FromVersion:7,ToVersion:11}));
assert.equal(actualQuestion.expectedFromVersion,7);assert.equal(actualQuestion.expectedToVersion,11);
const actualChoice=build(item('choice',{Members:[{PackageId:'winner',Approved:true,Accepted:true,TaskId:'real-task',EvidenceToken:'actual'}]}));
assert.equal(actualChoice.winner,'winner');assert.equal(actualChoice.expectedEvidenceToken,'actual');
const authorization=build(item('authorization',{PackageId:'A',PackageVersion:4,Id:'grant'}));
assert.equal(authorization.packageId,'A');assert.equal(authorization.expectedPackageVersion,4);assert.equal(authorization.authorizationId,'grant');
const adoption=build(item('adoption',{adoption:{Key:'policy',KnowledgeVersion:2}}));
assert.equal(adoption.key,'policy');assert.equal(adoption.expectedKnowledgeVersion,2);
const review=build(item('review',{TaskId:'task',part:{PartId:'object',RunId:'run',HeadSha:'abc'}}));
assert.equal(review.taskId,'task');assert.equal(review.expectedRunId,'run');assert.equal(review.expectedHeadSha,'abc');
assert.equal(review.expectedPartRevision,3);assert.equal(review.expectedEvidenceToken,'inbox-context-hash');assert.equal(review.decision,'Defer');
const reconsider=build(item('reconsider',{TaskId:'task',part:{RunId:'run',HeadSha:'head',ReviewId:'old-review'}}));
assert.equal(reconsider.expectedDecisionId,'old-review');assert.equal(reconsider.taskId,'task');assert.equal(reconsider.expectedRunId,'run');
assert.equal(reconsider.expectedEvidenceToken,'inbox-context-hash');assert.equal(reconsider.reason,'');
assert.throws(()=>build(item('reconsider',{TaskId:'task',part:{RunId:'run',HeadSha:'head'}})));
const repair=build(item('repair',{TaskId:'task',part:{RunId:'run',HeadSha:'head',ReviewId:'rework-review'}}));
assert.equal(repair.expectedDecisionId,'rework-review');assert.equal(repair.taskId,'task');assert.equal(repair.expectedRunId,'run');
assert.equal(repair.expectedEvidenceToken,'inbox-context-hash');assert.equal(repair.reason,'');
assert.throws(()=>build(item('repair',{TaskId:'task',part:{RunId:'run',HeadSha:'head'}})));
