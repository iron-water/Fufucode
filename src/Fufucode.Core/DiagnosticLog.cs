using System.Text.Json;
using System.Text.Json.Serialization;
using System.Threading.Channels;

namespace Fufucode.Core;

[JsonSourceGenerationOptions(PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase)]
[JsonSerializable(typeof(PiDiagnosticEvent))]
internal partial class DiagnosticJsonContext : JsonSerializerContext;

/// <summary>Bounded, asynchronous application diagnostics. Only the safe PiDiagnosticEvent schema is persisted.</summary>
public sealed class DiagnosticLog : IBackendDiagnosticSink, IAsyncDisposable
{
    private readonly Channel<PiDiagnosticEvent> _entries = Channel.CreateBounded<PiDiagnosticEvent>(
        new BoundedChannelOptions(2048) { SingleReader = true, FullMode = BoundedChannelFullMode.DropOldest });
    private readonly Task _writer;
    private readonly string _path;

    public DiagnosticLog(AppDataLayout layout)
    {
        layout.EnsureCreated();
        _path = Path.Combine(layout.LogsDirectory,
            "app-" + DateTime.UtcNow.ToString("yyyyMMdd") + "-" + Guid.NewGuid().ToString("N") + ".jsonl");
        _writer = WriteAsync();
    }

    public string FilePath => _path;
    public void Record(PiDiagnosticEvent entry)
    {
        // Allow-list fields before persistence; callers cannot accidentally leak a payload in a label.
        var safe = Sanitize(entry);
        _entries.Writer.TryWrite(safe);
    }

    /// <summary>Extension UI dialog methods that may appear as the Command of a UI diagnostic.</summary>
    private static readonly string[] UiMethods =
        ["confirm", "select", "input", "editor", "notify", "setStatus", "setWidget", "setTitle", "set_editor_text"];

    private static readonly string[] UiOutcomes =
        ["value", "confirmed", "declined", "cancelled", "expired", "closed", "notified", "ignored"];

    private static bool IsUiEvent(string eventType) =>
        eventType is "extension_ui_request" or "extension_ui_response";

    internal static PiDiagnosticEvent Sanitize(PiDiagnosticEvent entry)
    {
        var eventType = entry.EventType is "request_started" or "request_completed" or "request_failed" or
            "process_exited" or "connection_failed" or "extension_ui_request" or "extension_ui_response"
            ? entry.EventType : "other";
        var ui = IsUiEvent(eventType);
        return entry with
        {
            EventType = eventType,
            Command = ui ? (entry.Command is { } method && UiMethods.Contains(method, StringComparer.Ordinal)
                    ? method : entry.Command is null ? null : "other")
                : entry.Command is "get_state" or "get_available_models" or "get_commands" or "get_entries" or
                    "prompt" or "clear_queue" or "abort" or "set_session_name" ? entry.Command :
                    entry.Command is null ? null : "other",
            // Extension dialog IDs are generated by Pi or an extension, so they are bounded and filtered
            // instead of being compared against the RPC request-id shape.
            RequestId = ui ? SafeId(entry.RequestId)
                : entry.RequestId is { Length: 32 } id && id.All(Uri.IsHexDigit) ? id : null,
            ErrorCode = entry.ErrorCode is "command_rejected" or "timeout" or "canceled" or
                "transport_error" or "protocol_or_process" or "io_error" ? entry.ErrorCode :
                entry.ErrorCode is null ? null : "other",
            Outcome = entry.Outcome is null ? null
                : UiOutcomes.Contains(entry.Outcome, StringComparer.Ordinal) ? entry.Outcome : "other"
        };
    }

    private static string? SafeId(string? value)
    {
        if (value is not { Length: > 0 } id || id.Length > 64) return null;
        foreach (var c in id)
            if (!char.IsAsciiLetterOrDigit(c) && c is not '.' and not '_' and not '-' and not ':') return null;
        return id;
    }

    private async Task WriteAsync()
    {
        await using var stream = new FileStream(_path, FileMode.Append, FileAccess.Write, FileShare.Read,
            bufferSize: 8192, FileOptions.Asynchronous);
        await using var writer = new StreamWriter(stream);
        await foreach (var entry in _entries.Reader.ReadAllAsync())
        {
            await writer.WriteLineAsync(JsonSerializer.Serialize(entry, DiagnosticJsonContext.Default.PiDiagnosticEvent));
            await writer.FlushAsync();
        }
        await writer.FlushAsync();
    }

    public async ValueTask DisposeAsync()
    {
        _entries.Writer.TryComplete();
        await _writer;
    }
}
